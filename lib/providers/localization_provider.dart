import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';

class LocalizationProvider extends ChangeNotifier {
  Locale _locale = const Locale('en');
  static const String _prefKey = 'selected_language_code';

  Locale get locale => _locale;

  LocalizationProvider() {
    _loadSavedLocale();
  }

  Future<void> _loadSavedLocale() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final code = prefs.getString(_prefKey);
      if (code != null && ['en', 'si', 'ta'].contains(code)) {
        _locale = Locale(code);
        notifyListeners();
      }
    } catch (e) {
      debugPrint('Error loading saved locale: $e');
    }
  }

  Future<void> setLocale(Locale locale) async {
    _locale = locale;
    notifyListeners();
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_prefKey, locale.languageCode);
    } catch (e) {
      debugPrint('Error saving locale: $e');
    }
  }

  String translate(String key) {
    final lang = _locale.languageCode;
    final lowerKey = key.toLowerCase().trim();
    final snakeKey = lowerKey.replaceAll(' ', '_').replaceAll('&', 'and');
    if (_translations.containsKey(lang)) {
      if (_translations[lang]!.containsKey(key)) {
        return _translations[lang]![key]!;
      }
      if (_translations[lang]!.containsKey(lowerKey)) {
        return _translations[lang]![lowerKey]!;
      }
      if (_translations[lang]!.containsKey(snakeKey)) {
        return _translations[lang]![snakeKey]!;
      }
    }
    if (_translations['en']!.containsKey(key)) {
      return _translations['en']![key]!;
    }
    if (_translations['en']!.containsKey(lowerKey)) {
      return _translations['en']![lowerKey]!;
    }
    if (_translations['en']!.containsKey(snakeKey)) {
      return _translations['en']![snakeKey]!;
    }
    return key;
  }

